"""Convert opcode_hist.json (from profile_opcodes.py) into opcode_hist.inc.

The .inc file is the body of a C array initializer: 256 unsigned long long
opcode execution counts, measured from real SMB emulation on the GPU.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
data = json.loads((HERE / "opcode_hist.json").read_text())
counts = data["counts"]
assert len(counts) == 256

lines = [
    f"// Generated by make_hist_header.py from opcode_hist.json.",
    f"// Real SMB opcode execution counts: {data['num_envs']} envs, frameskip "
    f"{data['frameskip']}, {data['profile_steps']} profiled steps, "
    f"{data['total_executions']:,} total executions.",
]
for row in range(0, 256, 8):
    chunk = ", ".join(f"{c}ull" for c in counts[row:row + 8])
    lines.append(f"    {chunk},  // 0x{row:02X}-0x{row + 7:02X}")

(HERE / "opcode_hist.inc").write_text("\n".join(lines) + "\n")
print("wrote opcode_hist.inc")
